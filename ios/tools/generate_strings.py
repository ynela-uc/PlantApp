#!/usr/bin/env python3
"""
Generates ios/PlantApp/Core/Strings.generated.swift from the Android string resources, so both apps
always say the same thing in English, Arabic and Kurdish (Sorani).

Run from the repo root:  python3 ios/tools/generate_strings.py
Android placeholders become Swift format specifiers: %1$s -> %1$@, %1$d -> %1$ld.
"""
import json
import re
import sys
import xml.etree.ElementTree as ET
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
RES = ROOT / "android" / "app" / "src" / "main" / "res"
OUT = ROOT / "ios" / "PlantApp" / "Core" / "Strings.generated.swift"

FILES = {"en": RES / "values" / "strings.xml", "ar": RES / "values-ar" / "strings.xml", "ckb": RES / "values-ckb" / "strings.xml"}


def convert(text: str) -> str:
    text = text.replace("\\'", "'").replace('\\"', '"').replace("\\n", "\n")
    text = re.sub(r"%(\d+)\$s", r"%\1$@", text)
    text = re.sub(r"%(\d+)\$d", r"%\1$ld", text)
    return text


def load(path: Path) -> dict:
    result = {}
    for node in ET.parse(path).getroot().findall("string"):
        result[node.get("name")] = convert(node.text or "")
    return result


def main() -> int:
    tables = {lang: load(path) for lang, path in FILES.items()}
    keys = sorted(set().union(*[set(t) for t in tables.values()]))
    lines = [
        "// GENERATED by ios/tools/generate_strings.py from the Android string resources. Do not edit by hand.",
        "",
        "enum GeneratedStrings {",
        "    /// key -> language code (en / ar / ckb) -> text",
        "    static let table: [String: [String: String]] = [",
    ]
    for key in keys:
        entries = ", ".join(
            f"{json.dumps(lang)}: {json.dumps(tables[lang][key], ensure_ascii=False)}"
            for lang in ("en", "ar", "ckb")
            if key in tables[lang]
        )
        lines.append(f"        {json.dumps(key)}: [{entries}],")
    lines += ["    ]", "}", ""]
    OUT.parent.mkdir(parents=True, exist_ok=True)
    OUT.write_text("\n".join(lines), encoding="utf-8")
    missing = [(l, k) for l, t in tables.items() for k in keys if k not in t]
    print(f"{len(keys)} strings written to {OUT}")
    if missing:
        print("missing translations:", missing[:20], "..." if len(missing) > 20 else "")
    return 0


if __name__ == "__main__":
    sys.exit(main())

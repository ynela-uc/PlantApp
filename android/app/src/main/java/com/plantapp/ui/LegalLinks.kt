private val ErrorRed = Color(0xFFC62828)

/** Where the privacy policy and terms pages are published (generated by tools/build_legal.py into docs/legal). */
const val LEGAL_BASE_URL = "https://ynela-uc.github.io/PlantApp/legal/"

fun legalUrl(kind: String, lang: String): String = "$LEGAL_BASE_URL$kind-$lang.html"

@Composable
private fun rememberOpenLegal(kind: String): () -> Unit {
    val context = LocalContext.current
    val lang = rememberLang()
    return {
        try { context.startActivity(Intent(Intent.ACTION_VIEW, Uri.parse(legalUrl(kind, lang)))) } catch (_: ActivityNotFoundException) { }
    }
}

/** Two small links: privacy policy and terms of use. */
@Composable
fun LegalLinks(accent: Color) {
    val openPrivacy = rememberOpenLegal("privacy")
    val openTerms = rememberOpenLegal("terms")
    Row(modifier = Modifier.fillMaxWidth(), horizontalArrangement = Arrangement.Center) {
        TextButton(onClick = openPrivacy) { Text(stringResource(R.string.legal_privacy), color = accent) }
        TextButton(onClick = openTerms) { Text(stringResource(R.string.legal_terms), color = accent) }
    }
}

/** The line under the sign-up button. */
@Composable
fun LegalAgreement(accent: Color) {
    Column(modifier = Modifier.fillMaxWidth().padding(top = 12.dp)) {
        Text(stringResource(R.string.legal_agree), style = MaterialTheme.typography.bodySmall, color = TextMuted)
        LegalLinks(accent)
    }
}

/** "Delete my account": asks to confirm, deletes on the server, then signs out through [onDeleted]. */
@Composable
fun DeleteAccountSection(onDeleted: () -> Unit) {
    var confirm by rememberSaveable { mutableStateOf(false) }
    var busy by rememberSaveable { mutableStateOf(false) }
    var message by rememberSaveable { mutableStateOf<Int?>(null) }
    val scope = rememberCoroutineScope()

    Column(modifier = Modifier.fillMaxWidth()) {
        message?.let {
            Text(stringResource(it), color = ErrorRed, style = MaterialTheme.typography.bodyMedium, modifier = Modifier.padding(bottom = 8.dp))
        }
        OutlinedButton(onClick = { confirm = true }, enabled = !busy, modifier = Modifier.fillMaxWidth()) {
            Text(stringResource(R.string.delete_account), color = ErrorRed, fontWeight = FontWeight.SemiBold)
        }
    }

    if (confirm) {
        AlertDialog(
            onDismissRequest = { confirm = false },
            title = { Text(stringResource(R.string.delete_title)) },
            text = { Text(stringResource(R.string.delete_body)) },
            confirmButton = {
                TextButton(onClick = {
                    confirm = false
                    busy = true
                    message = null
                    scope.launch {
                        try {
                            Backend.client.postgrest.rpc("delete_my_account")
                            onDeleted()
                        } catch (e: Exception) {
                            message = if (e.message.orEmpty().contains("open_orders")) R.string.delete_blocked else R.string.delete_failed
                        }
                        busy = false
                    }
                }) { Text(stringResource(R.string.delete_yes), color = ErrorRed) }
            },
            dismissButton = { TextButton(onClick = { confirm = false }) { Text(stringResource(R.string.delete_no)) } },
        )
    }
    Spacer(Modifier.height(4.dp))
}
